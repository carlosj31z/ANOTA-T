// Geocodificación aproximada por lugar para Perú. Se usa para asignar
// coordenadas a agencias sin lat/lng (importadas o del directorio oficial),
// de modo que el ordenamiento por cercanía funcione al menos a nivel de
// ciudad/distrito, con respaldo al centroide del departamento.

function norm(s) {
  return String(s || '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .trim()
}

