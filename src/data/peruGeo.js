/**
 * Devuelve { lat, lng } aproximado para el lugar dado. Intenta por distrito,
 * luego por departamento, y por último el centro del Perú.
 */
export function geocodePlace({ department, province, district } = {}) {
  const d = DISTRICTS[norm(district)] || DISTRICTS[norm(province)]
  if (d) return { lat: d[0], lng: d[1] }
  const dep = DEPARTMENTS[norm(department)]
  if (dep) return { lat: dep[0], lng: dep[1] }
  return { lat: -9.19, lng: -75.02 } // centro aproximado del Perú
}
